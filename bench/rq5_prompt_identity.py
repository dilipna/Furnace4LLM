"""RQ5 check: do the accepted repairs send exactly the base revision's prompts?

For each verified attempt in a campaign's `rq5/r1_dynamic_head_r*.json`, rebuild the PR head
(F1 + the R1 edits), apply the stored repair patch with `git apply`, and render every
documented question's chat messages with each tree's own `app/prompts.build_messages` (the
retrieval step is shared: the PR does not touch it). Prints, per attempt, how many of the
questions render byte-identical messages on base and repair, and the repair's lines that
differ from base outside `build_messages`' output (imports, logging).

Runs in the fixture's own environment (its retriever needs `rank_bm25`):

    FURNACE_BENCH_DATE=2026-10-12-gate-validation PYTHONPATH=bench \
        fixtures/apps/support-rag-py/.venv/Scripts/python.exe bench/rq5_prompt_identity.py
"""

from __future__ import annotations

import difflib
import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

from common import ROOT, results_dir

sys.path.insert(0, str(ROOT / "fixtures" / "scenarios"))
from f1_scenarios import F1, by_name, materialize


def _build_messages(tree: Path) -> Any:
    spec = importlib.util.spec_from_file_location(
        f"prompts_{tree.name}", tree / "app" / "prompts.py"
    )
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(tree))
    try:
        spec.loader.exec_module(mod)
    finally:
        sys.path.remove(str(tree))
    return mod.build_messages


def main() -> int:
    out = results_dir("rq5")
    questions = [q["question"] for q in json.loads((F1 / "docs" / "facts.json").read_text("utf-8"))]
    sys.path.insert(0, str(F1))
    import yaml

    # the base retriever (R1 does not change retrieval), importable only from the fixture path
    from app.retriever import retrieve  # pyright: ignore[reportMissingImports]

    cfg = yaml.safe_load((F1 / "config" / "rag.yaml").read_text("utf-8"))["retrieval"]
    base_build = _build_messages(F1)
    lines = []
    for f in sorted(out.glob("r1_dynamic_head_r*.json")):
        if f.name.endswith(".perf_reports.json"):
            continue
        rec = json.loads(f.read_text("utf-8"))
        if rec["status"] != "verified":
            lines.append(f"{f.name}: {rec['status']}, no accepted patch")
            continue
        with tempfile.TemporaryDirectory() as tmp:
            tree = materialize(by_name("r1_dynamic_head"), Path(tmp) / "repair")
            patch = Path(tmp) / "repair.patch"
            patch.write_text(rec["patch"], encoding="utf-8")
            git = ["git", "apply", "--whitespace=nowarn", str(patch)]
            subprocess.run(git, cwd=tree, check=True)  # noqa: S603 - fixed argv
            rep_build = _build_messages(tree)
            same = 0
            for q in questions:
                chunks = retrieve(q, top_k=cfg["top_k"])
                same += base_build(q, chunks, cfg["max_context_chars"]) == rep_build(
                    q, chunks, cfg["max_context_chars"]
                )
            diff = [
                d
                for d in difflib.unified_diff(
                    (F1 / "app" / "prompts.py").read_text("utf-8").splitlines(),
                    (tree / "app" / "prompts.py").read_text("utf-8").splitlines(),
                    lineterm="",
                    n=0,
                )
                if d[:1] in "+-" and not d.startswith(("+++", "---"))
            ]
        lines.append(
            f"{f.name}: {same}/{len(questions)} questions render identical messages on base and "
            f"repair; app/prompts.py differs from base by {len(diff)} line(s): "
            + " | ".join(d.strip() for d in diff)
        )
    print("\n".join(lines))
    (out / "prompt_identity.md").write_text(
        "# RQ5: accepted repairs vs base, rendered prompts\n\n"
        "Generated by `bench/rq5_prompt_identity.py`.\n\n"
        + "\n".join(f"- {x}" for x in lines)
        + "\n",
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
