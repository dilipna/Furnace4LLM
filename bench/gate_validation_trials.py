"""Every gate-validation trial, one row each, from the stored records (no measurement).

Writes `validation/trials.md` next to the set files: per set, every trial with its status
(counted / affected), verdict, change, interval and the SM clock of its six runs; then the
unchanged-code trials (V1 + V2) on their own, so every non-PASS outcome is listed; then how the
trial count adds up and the clock range. Verdicts are read as recorded, never recomputed here
(`gate_validation_report.py` does the recomputation).

    FURNACE_BENCH_DATE=2026-10-12-gate-validation uv run python bench/gate_validation_trials.py
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from common import results_dir

SETS = ["v1_aa", "v2_restored", "v3a_r1", "v3b_r2", "v3c_topk4", "v3c_topk8"]
UNCHANGED = {"v1_aa", "v2_restored"}


def _load(d: Path, name: str) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    summary = json.loads((d / f"{name}.json").read_text(encoding="utf-8"))
    rows = [
        json.loads(line)
        for line in (d / f"{name}.jsonl").read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    return summary, rows


def _row(name: str, t: dict[str, Any], affected: set[int]) -> list[str]:
    clocks = t.get("sm_clock_mhz") or []
    lo, hi = (min(clocks), max(clocks)) if clocks else (None, None)
    ci = t.get("ci_pct") or [None, None]
    return [
        name,
        str(t["trial"]),
        "affected (kept, not counted)" if t["trial"] in affected else "counted",
        str(t.get("started_utc", "")),
        t["verdict"].upper(),
        f"{t['change_pct']:+.1f}%",
        f"{ci[0]:+.1f} to {ci[1]:+.1f}" if ci[0] is not None else "–",
        f"{lo:.0f}-{hi:.0f}" if lo is not None else "–",
        "AC" if (t.get("power_after") or {}).get("on_ac") else "NOT AC",
    ]


HEAD = [
    "set",
    "trial",
    "status",
    "start (UTC)",
    "verdict",
    "change",
    "90% interval (pts)",
    "SM MHz (6 runs)",
    "power after",
]


def _table(rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(HEAD) + " |", "|" + "---|" * len(HEAD)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def main() -> int:
    d = results_dir("validation")
    all_rows: list[list[str]] = []
    unchanged: list[list[str]] = []
    counts: list[str] = []
    clocks: list[float] = []
    total = counted_total = 0
    for name in SETS:
        summary, trials = _load(d, name)
        affected = {a["trial"] for a in summary.get("affected", [])}
        n_aff = sum(t["trial"] in affected for t in trials)
        counted = len(trials) - n_aff
        total += len(trials)
        counted_total += counted
        counts.append(
            f"- `{name}`: {len(trials)} trials recorded = {counted} counted"
            f" (planned {summary['requested_trials']})"
            + (f" + {n_aff} affected ({', '.join(map(str, sorted(affected)))})" if n_aff else "")
        )
        for t in trials:
            clocks += t.get("sm_clock_mhz") or []
            r = _row(name, t, affected)
            all_rows.append(r)
            if name in UNCHANGED:
                unchanged.append(r)
    not_pass = [r for r in unchanged if r[4] != "PASS"]
    not_pass_counted = [r for r in not_pass if r[2] == "counted"]
    lines = [
        "# Gate validation: every trial",
        "",
        "Generated by `bench/gate_validation_trials.py` from `<set>.json` / `<set>.jsonl`; verdicts",
        "as recorded (the recomputation is in `report.md`). Nothing here changes a figure.",
        "",
        "## How the trials add up",
        "",
        *counts,
        f"- **{total} trials recorded = {counted_total} counted + {total - counted_total} affected**."
        " Affected trials ran while other compute was on the machine (rule and evidence:"
        " `../NOTES.md`); they are kept with their results, left out of the primary tally and"
        " replaced by one extra trial each in the same set.",
        "- Not in any count: V1 trial 15's first attempt, cut off by Windows Sleep at 19:54 UTC on"
        " 2026-10-12 before it finished (no record was written; the trial was run again).",
        "",
        f"SM clock over all {len(clocks)} runs of all trials: {min(clocks):.0f}-{max(clocks):.0f} MHz"
        f" ({sum(c == 780 for c in clocks)} runs at exactly 780 MHz).",
        "",
        "## Unchanged code (V1 fresh A/A + V2 restored baseline): every outcome",
        "",
        f"{len(unchanged)} trials, of which {len(unchanged) - sum(r[2] != 'counted' for r in unchanged)}"
        f" counted. Not PASS among the counted: **{len(not_pass_counted)}**"
        f" ({', '.join(r[0] + ' #' + r[1] + ' ' + r[4] for r in not_pass_counted) or 'none'});"
        " none is a FAIL.",
        "",
        *_table(unchanged),
        "",
        "## All trials",
        "",
        *_table(all_rows),
        "",
    ]
    (d / "trials.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:22]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
