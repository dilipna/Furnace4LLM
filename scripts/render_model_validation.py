"""Render docs/product/real-model-validation.md from the recorded JSON validation runs.

    python scripts/render_model_validation.py

Every number in the page comes from docs/product/verification/real-model-*.json.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / "docs" / "product" / "verification"
OUT = ROOT / "docs" / "product" / "real-model-validation.md"


def load() -> list[tuple[str, dict]]:
    def finite(value: str) -> float:
        result = float(value)
        if not math.isfinite(result):
            raise ValueError("Model evidence contains a nonfinite number")
        return result

    runs = []
    for path in sorted(DIR.glob("real-model-*.json")):
        record = json.loads(
            path.read_text(encoding="utf-8"), parse_float=finite, parse_constant=finite
        )
        if record.get("schema") != "furnace-real-model-validation-v1":
            raise ValueError(f"Unsupported model evidence schema: {path.name}")
        checks = [
            passed
            for step in record["steps"].values()
            if isinstance(step, dict)
            for passed in step.get("checks", {}).values()
        ]
        if any(type(value) is not bool for value in checks):
            raise ValueError(f"Model checks must be booleans: {path.name}")
        if record["result"] == "passed" and (not checks or not all(checks) or record["failures"]):
            raise ValueError(f"Contradictory passed model record: {path.name}")
        for name in ("evaluation_1", "evaluation_2"):
            evaluation = record["steps"].get(name)
            if not evaluation:
                continue  # Failed records may stop before evaluation.
            results = evaluation["per_case"]
            if (
                evaluation["status"] == "completed"
                and len(results) != record["steps"]["suite"]["cases"]
            ):
                raise ValueError(f"Incomplete completed evaluation: {path.name}")
            for count, statuses in (
                ("passed", {"check_pass", "exact_pass"}),
                ("failed", {"check_fail", "exact_fail"}),
                ("incomplete", {"incomplete"}),
                ("errors", {"error"}),
            ):
                if evaluation[count] != sum(case["status"] in statuses for case in results):
                    raise ValueError(f"Model evaluation count mismatch: {path.name}")
        runs.append((path.name, record))
    if not runs:
        raise ValueError("No model evidence records found")
    return runs


def label(r: dict) -> str:
    fresh = " · fresh download" if r["steps"].get("prepare", {}).get("fresh_download") else ""
    return f"{r['model']} · {r['accelerator']}{fresh}"


def fmt(value, suffix=""):
    return "—" if value is None else f"{value}{suffix}"


def render() -> str:
    runs = load()
    lines = [
        "# Real-model validation: Furnace-operated local servers",
        "",
        "Generated by `scripts/render_model_validation.py` from the recorded runs in",
        "[`verification/`](verification/). Each run was produced by",
        "`scripts/validate_managed_model.py`, which starts a real Studio process and drives the",
        "whole local journey through its HTTP API using pinned weights and a llama.cpp",
        "server container, with recorded failure injection and Studio crash recovery.",
        "These are historical records for the source and hardware below. Rendering/checking",
        "them does not execute inference or validate a newer integrated application build.",
        "",
    ]
    env = runs[0][1]["environment"]
    lines += [
        "## Machine",
        "",
        f"- OS: {env['os']} ({env['machine']}), Python {env['python']}",
        f"- Docker: {env['docker_server']} on {env['docker_os']}; VM {env['docker_vm_cpus']} CPUs, "
        f"{round((env['docker_vm_memory_bytes'] or 0) / 2**30, 1)} GiB; NVIDIA runtime: {env['docker_gpu_runtime']}",
        f"- GPU: {env['host_gpu']}",
        f"- Furnace commit: `{env['furnace_commit']}` (clean tree: {env['working_tree_clean']})",
        "",
        "## Summary",
        "",
        "| run | result | checks | ready (s) | restart (s) | suite score | eval (s) | repro: repeat / relaunch / re-execution | crash | resident memory |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name, r in runs:
        s = r["steps"]
        checks = {
            k: v
            for step in s.values()
            if isinstance(step, dict)
            for k, v in step.get("checks", {}).items()
        }
        e1, e2 = s.get("evaluation_1", {}), s.get("evaluation_2", {})
        rep2 = e2.get("reproducibility") or {}
        rep3 = s.get("restart", {}).get("reproducibility") or {}
        outs = s.get("outputs", {})
        crash = s.get("crash_during_evaluation", {})
        lines.append(
            f"| [{label(r)}](verification/{name}) | **{r['result']}** | "
            f"{sum(checks.values())}/{len(checks)} | {fmt(s.get('start', {}).get('start_seconds'))} | "
            f"{fmt(s.get('restart', {}).get('seconds'))} | {e1.get('passed', '—')}/{len(e1.get('per_case', []))} | "
            f"{fmt(e1.get('elapsed_seconds'))} | {rep2.get('identical', '—')}/{rep2.get('compared', '—')} · "
            f"{rep3.get('identical', '—')}/{rep3.get('compared', '—')} · {outs.get('identical_to_evaluation', '—')}/{len(outs.get('cases', []))} | "
            f"{crash.get('reason', '—')} → {crash.get('last', {}).get('status', '—')} | "
            f"{(s.get('observe', {}).get('resources') or {}).get('memory', '—')} |"
        )
    lines += [
        "",
        "Suite score counts rule checks that passed out of twelve; it measures the model, not the",
        "infrastructure. Reproducibility compares SHA-256 hashes of outputs: a second run, a run after",
        "the server was killed and relaunched, and independent ad-hoc re-execution of each case.",
        "",
        "## Checks recorded",
        "",
    ]
    union: dict[str, dict[str, int]] = {}
    for _name, r in runs:
        for step, value in r["steps"].items():
            if isinstance(value, dict):
                for check in value.get("checks", {}):
                    union.setdefault(step, {}).setdefault(check, 0)
                    union[step][check] += 1
    for step, checks in union.items():
        items = [
            c if n == len(runs) else f"{c} ({n} of {len(runs)} runs)" for c, n in checks.items()
        ]
        lines.append(f"- **{step.replace('_', ' ')}**: " + "; ".join(items))
    lines.append("")
    lines.append(
        "The download checks apply to the fresh-download run; the GPU memory check to NVIDIA runs."
    )
    for _name, r in runs:
        s = r["steps"]
        lines += ["", f"## {label(r)}", ""]
        lines.append(
            f"Recipe: `{r['recipe']['repository']}@{r['recipe']['revision'][:12]}`, weights SHA-256 "
            f"`{r['recipe']['weights_sha256'][:16]}…`, {r['recipe']['architecture']}, {r['recipe']['license']}. "
            f"Manifest `{(s.get('prepare') or {}).get('manifest_sha256', '')[:16]}…`."
        )
        prep = s.get("prepare", {})
        if prep.get("fresh_download"):
            lines.append(
                f"Fresh download into an empty store, cancelled at {prep.get('interrupted_at_bytes')} bytes, "
                f"then resumed and verified; preparation took {prep.get('seconds')} s in total."
            )
        iso = s.get("start", {}).get("isolation")
        if iso:
            lines.append(
                f"Isolation observed: user {iso['user']}, read-only root {iso['read_only_root']}, capabilities "
                f"dropped {iso['cap_drop']}, memory {iso['memory_bytes'] // 2**20} MiB, networks {iso['networks']}, "
                f"GPU requested {iso['gpus_requested']}."
            )
        memory = s.get("start", {}).get("host_gpu_memory_mib") or {}
        growth = s.get("observe", {}).get("gpu_memory_growth_mib")
        if growth is not None:
            lines.append(
                f"Host GPU memory {memory.get('before_start')} MiB before start, "
                f"{memory.get('after_ready')} MiB once ready (+{growth} MiB)."
            )
        lines.append(
            f"Recorded from commit `{r['environment']['furnace_commit'][:12]}` "
            f"(clean tree: {r['environment']['working_tree_clean']})."
        )
        lines += [
            "",
            "| case | rule | status | reason | duration (ms) | output |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        cases = s.get("outputs", {}).get("cases", [])
        for case, res in zip(cases, s.get("evaluation_1", {}).get("per_case", []), strict=False):
            text = case["output"].replace("\n", " ").replace("|", "\\|")
            lines.append(
                f"| {case['case']} | {res['scoring_method']} | {res['status']} | {res['reason']} | "
                f"{res['duration_ms']} | `{text[:80]}` |"
            )
        failed = r.get("failures") or []
        if failed:
            lines.append("")
            lines.append("Failed checks: " + ", ".join(failed))
    lines += [
        "",
        "## Hardware requirements observed",
        "",
        "- Both models ran in a 2 GiB container on CPU (4 threads) and with all layers on a 4 GiB",
        "  laptop GPU. Resident memory after the runs is in the summary table; GPU runs reserve more",
        "  container memory for CUDA buffers.",
        "- Docker Desktop with the WSL2 engine and Linux containers; the NVIDIA option needs the",
        "  NVIDIA driver with WSL GPU support (Docker reports the `nvidia` runtime).",
        "- Disk: about 1 GiB of weights for both models, plus the server images (CPU image about",
        "  0.3 GB; CUDA image several GB).",
        "",
        "## Limitations",
        "",
        "- One machine and one operating system: Windows 11 with Docker Desktop (WSL2). Linux and",
        "  macOS hosts were not used for real-model runs; the container isolation tests also run on",
        "  Ubuntu in CI with a test adapter, not a model.",
        "- Small models (0.35B and 0.49B parameters) and one twelve-case suite. Suite scores are",
        "  rule checks, not human or semantic quality judgements, and say nothing about larger models.",
        "- Timings are single-request, non-streaming round trips on a laptop; they are not",
        "  throughput, TTFT or a performance comparison between CPU and GPU.",
        "- Single user, sequential requests; concurrency and long soak runs were not tested.",
        "- Furnace verifies the weights it mounts and pins the engine image digest; it does not",
        "  attest the code inside the engine image.",
        "- The researcher Python adapter path is tested with a deterministic test adapter only.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Validate records and refuse a stale report"
    )
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Model report is stale; run scripts/render_model_validation.py")
        print("PASS: model records are consistent and the report matches; no inference performed")
    else:
        OUT.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
