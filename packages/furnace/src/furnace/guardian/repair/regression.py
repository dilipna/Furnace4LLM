"""Regression tests Furnace writes *before* attempting any repair."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from furnace.sandbox.docker_sandbox import run_in_sandbox

REGRESSION_DIR = "tests/furnace_regression"

_RENDER_SCRIPT = """import json
from furnace_harness import render

questions = json.load(open("_furnace_questions.json", encoding="utf-8"))
print("FURNACE_RENDER " + json.dumps([render(q) for q in questions]))
"""


def render_in_sandbox(repo: Path, questions: list[str]) -> list[list[dict]]:
    """Render messages for `questions` through the repo's harness, inside the sandbox.
    Inputs travel as files in the sandbox copy, not as command-line arguments."""
    r = run_in_sandbox(
        repo,
        ["python", "_furnace_render.py"],
        timeout_s=180,
        files={
            "_furnace_render.py": _RENDER_SCRIPT,
            "_furnace_questions.json": json.dumps(questions),
        },
        output_limit=20 * 2**20,
    )
    line = next((ln for ln in r.stdout.splitlines() if ln.startswith("FURNACE_RENDER ")), None)
    if not r.ok or line is None:
        raise RuntimeError(f"harness render failed in sandbox: {(r.stderr or r.stdout)[-800:]}")
    return json.loads(line.removeprefix("FURNACE_RENDER "))


_ANSWER_SCRIPT = """import json, re
from concurrent.futures import ThreadPoolExecutor
from furnace_harness import answer, render

CITATION = re.compile(r"\\[doc:([A-Za-z0-9_.\\-]+)\\]")
questions = json.load(open("_furnace_questions.json", encoding="utf-8"))

def one(q):
    retrieved = CITATION.findall(render(q)[-1]["content"])
    return {"question": q, "answer": answer(q), "retrieved": retrieved}

with ThreadPoolExecutor(8) as pool:
    rows = list(pool.map(one, questions))
print("FURNACE_ANSWERS " + json.dumps(rows))
"""


def answers_in_sandbox(
    repo: Path, questions: list[str], env: dict[str, str], network: str
) -> list[dict]:
    """Run the app's full answer path (harness.answer) for each question inside the
    sandbox, with network access only to the internal lab network."""
    r = run_in_sandbox(
        repo,
        ["python", "_furnace_answer.py"],
        network=network,
        env=env,
        timeout_s=600,
        files={
            "_furnace_answer.py": _ANSWER_SCRIPT,
            "_furnace_questions.json": json.dumps(questions),
        },
        output_limit=20 * 2**20,
    )
    line = next((ln for ln in r.stdout.splitlines() if ln.startswith("FURNACE_ANSWERS ")), None)
    if not r.ok or line is None:
        raise RuntimeError(f"answer path failed in sandbox: {(r.stderr or r.stdout)[-800:]}")
    return json.loads(line.removeprefix("FURNACE_ANSWERS "))


def as_text(messages: list[dict]) -> str:
    return "".join(f"{m['role']}\n{m['content']}\n" for m in messages)


def common_prefix(a: str, b: str) -> int:
    n = min(len(a), len(b))
    i = 0
    while i < n and a[i] == b[i]:
        i += 1
    return i


def min_shared_prefix(rendered: list[list[dict]]) -> int:
    texts = [as_text(m) for m in rendered]
    return min(common_prefix(texts[0], t) for t in texts[1:])


TEMPLATE = '''"""Generated by Furnace Guard: regression test written before any fix was attempted.

Failure mode: {failure_mode}
Change under test: {change}

Every request must start with the same prompt text so the serving engine can reuse
the cached prefill of that shared prefix (prefix/KV caching). On the base revision,
two different requests shared {base_shared} leading characters; this test requires at
least {threshold} (90% of that).
"""

from furnace_harness import render

MIN_SHARED_CHARS = {threshold}
QUESTIONS = {questions!r}


def _text(question: str) -> str:
    return "".join(f"{{m['role']}}\\n{{m['content']}}\\n" for m in render(question))


def _shared(a: str, b: str) -> int:
    n = min(len(a), len(b))
    i = 0
    while i < n and a[i] == b[i]:
        i += 1
    return i


def test_prompt_prefix_is_shared_across_requests():
    first = _text(QUESTIONS[0])
    for q in QUESTIONS[1:]:
        shared = _shared(first, _text(q))
        assert shared >= MIN_SHARED_CHARS, (
            f"requests diverge after {{shared}} characters (need {{MIN_SHARED_CHARS}}); "
            f"first difference: {{first[shared:shared + 60]!r}}"
        )
'''


def prefix_stability_test(
    *, questions: list[str], base_shared: int, failure_mode: str, change: str
) -> tuple[str, str]:
    """Return (relative path, source) of the regression test."""
    threshold = int(base_shared * 0.9)
    src = TEMPLATE.format(
        failure_mode=failure_mode,
        change=change,
        base_shared=base_shared,
        threshold=threshold,
        questions=questions,
    )
    digest = hashlib.sha256(src.encode()).hexdigest()[:8]
    return f"{REGRESSION_DIR}/test_prefix_stability_{digest}.py", src
